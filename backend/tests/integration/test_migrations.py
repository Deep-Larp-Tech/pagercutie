import asyncio
import uuid
from collections.abc import Callable, Iterator

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import URL, make_url, text
from sqlalchemy.ext.asyncio import create_async_engine
from testcontainers.community.postgres import PostgresContainer


async def _execute_autocommit(url: URL, statement: str) -> None:
    engine = create_async_engine(url, isolation_level="AUTOCOMMIT")
    async with engine.connect() as connection:
        await connection.execute(text(statement))
    await engine.dispose()


@pytest.fixture
def empty_database_url(postgres: PostgresContainer) -> Iterator[str]:
    """A database of its own: the shared one is migrated once per session and must stay at head."""
    url = make_url(postgres.get_connection_url())
    name = f"migrations_{uuid.uuid7().hex}"
    asyncio.run(_execute_autocommit(url, f'CREATE DATABASE "{name}"'))
    yield url.set(database=name).render_as_string(hide_password=False)
    asyncio.run(_execute_autocommit(url, f'DROP DATABASE "{name}" WITH (FORCE)'))


def test_models_match_migrations(database_url: str, make_alembic_config: Callable[[str], Config]) -> None:
    """Fails with `AutogenerateDiffsDetected` when a model changed without a migration (CHECK constraints excepted)."""
    command.check(make_alembic_config(database_url))


def test_migrations_downgrade_and_upgrade_again(
    empty_database_url: str, make_alembic_config: Callable[[str], Config]
) -> None:
    config = make_alembic_config(empty_database_url)

    command.upgrade(config, "head")
    command.downgrade(config, "base")
    command.upgrade(config, "head")

    command.check(config)
