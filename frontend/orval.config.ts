import { defineConfig, type InputTransformerFn } from 'orval'

// FastAPI documents SSE responses with OpenAPI 3.2's `itemSchema`, which orval's 3.1 validator rejects.
// Those streams are read with EventSource, not the generated client; their item models stay in `model/`.
const dropSseItemSchemas: InputTransformerFn = (spec) => {
  for (const path of Object.values(spec.paths ?? {})) {
    for (const operation of Object.values(path ?? {})) {
      const content = (operation as { responses?: Record<string, { content?: Record<string, object> }> })
        .responses?.['200']?.content
      if (content?.['text/event-stream']) {
        content['text/event-stream'] = { schema: { type: 'string' } }
      }
    }
  }
  return spec
}

const input = { target: '../contract/openapi.json', override: { transformer: dropSseItemSchemas } }

// Generated from contract/openapi.json (`mise run contract`); never edit src/api/generated by hand.
export default defineConfig({
  api: {
    input,
    output: {
      mode: 'tags-split',
      target: 'src/api/generated/endpoints.ts',
      schemas: 'src/api/generated/model',
      client: 'react-query',
      httpClient: 'fetch',
      baseUrl: '/api',
      override: { mutator: { path: 'src/api/fetcher.ts', name: 'customFetch' } },
      mock: true,
      clean: true,
    },
  },
  apiZod: {
    input,
    output: {
      mode: 'tags-split',
      target: 'src/api/generated/zod.ts',
      client: 'zod',
      fileExtension: '.zod.ts',
    },
  },
})
